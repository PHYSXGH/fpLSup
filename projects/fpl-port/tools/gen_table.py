"""(Re)generate fpSup/fp_usb_shell/cameras/fpl302.tsv.

Scans the given trees for 0xC0000000..0xCFFFFFFF constants, maps each with
AddrMap, and writes `auto` rows for high-confidence results and `todo` rows for
the rest.  Rows already marked checked / camera / const / range, or a todo with
a hand-written reason, are kept as they are: regeneration never overwrites review.

    gen_table.py fpSup/fp_usb_shell fpSup/gyro
"""
import sys, re
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from addrmap import AddrMap, ROOT, BASE

OUT = ROOT / 'fpSup/fp_usb_shell/cameras/fpl302.tsv'
HEAD = """# SIGMA fp Ver.5.02 -> SIGMA fp L Ver.3.02 address table.  Read by fwtarget.py.
# Generated by projects/fpl-port/tools/gen_table.py; hand-reviewed rows (checked,
# camera, const, range, and todo rows with a reason) survive regeneration.
# fp_502\tfpl_302\tstatus\tnote
"""
pat = re.compile(r'\b0[xX]([Cc][0-9A-Fa-f]{7})\b')

kept, kept_ranges = {}, []
if OUT.exists():
    for line in OUT.read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        f = line.split('\t')
        if f[2] == 'range':
            kept_ranges.append(line)
        elif f[2] in ('checked', 'camera', 'const') or (f[2] == 'todo' and not f[3].startswith('auto:')):
            kept[int(f[0], 16)] = line

found = set()
for top in sys.argv[1:]:
    for f in (ROOT / top).rglob('*'):
        if f.suffix in ('.py', '.S') and f.is_file() and not f.name.startswith('test_'):
            found.update(int(x, 16) for x in pat.findall(f.read_text(errors='ignore')))
found.update(kept)

m = AddrMap()
rows, n = [], {'auto': 0, 'todo': 0, 'kept': 0}
def in_range(a):
    for r in kept_ranges:
        s, e = (int(x, 16) for x in r.split('\t')[:2])
        if s <= a < e: return True
for a in sorted(found):
    if a in kept:
        rows.append(kept[a]); n['kept'] += 1; continue
    if in_range(a):
        continue
    r, how = m.map(a); how = how or ''
    high = how == 'exact' or how.startswith('ram(') or ('+' in how and 'CONFLICT' not in how) \
        or (how.startswith('ptr(') and int(how[4:-1]) >= 3)
    if r is not None and high:
        rows.append(f'{a:#010x}\t{r:#010x}\tauto\t{how}'); n['auto'] += 1
    else:
        guess = f'{r:#010x}' if r is not None else '-'
        rows.append(f'{a:#010x}\t-\ttodo\tauto: guess {guess} by {how}'); n['todo'] += 1
OUT.write_text(HEAD + ''.join(r + '\n' for r in kept_ranges) + ''.join(r + '\n' for r in rows))
print(n, '->', OUT.relative_to(ROOT))
